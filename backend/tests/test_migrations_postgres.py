def test_every_scoped_table_has_not_null_tenant_id(isolated_pg_engine):
    """Every directly-scoped table carries a NOT NULL tenant_id defaulting to
    the default tenant, with an ix_<table>_tenant_id index and a RESTRICT FK
    named fk_<table>_tenant_id."""
    with isolated_pg_engine.connect() as conn:
        columns = {
            (row.table_name, row.column_name): row
            for row in conn.execute(
                text(
                    "SELECT table_name, column_name, is_nullable, column_default "
                    "FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND column_name = 'tenant_id'"
                )
            ).all()
        }
        indexes = set(
            conn.execute(
                text("SELECT indexname FROM pg_indexes WHERE schemaname = 'public'")
            )
            .scalars()
            .all()
        )
        restrict_fks = set(
            conn.execute(
                text(
                    "SELECT conname FROM pg_constraint "
                    "WHERE contype = 'f' AND confdeltype = 'r'"
                )
            )
            .scalars()
            .all()
        )

    for table in TENANT_SCOPED_TABLES:
        column = columns.get((table, "tenant_id"))
        assert column is not None, f"{table} has no tenant_id column"
        assert column.is_nullable == "NO", f"{table}.tenant_id is nullable"
        assert str(DEFAULT_TENANT_ID) in (column.column_default or ""), (
            f"{table}.tenant_id default is {column.column_default!r}"
        )
        assert f"ix_{table}_tenant_id" in indexes, f"{table} lacks its tenant index"
        assert f"fk_{table}_tenant_id" in restrict_fks, (
            f"{table}'s tenant FK is missing or is not ON DELETE RESTRICT"
        )


def test_inherited_tables_have_no_tenant_id(isolated_pg_engine):
    """The inherited tables must stay free of a denormalised tenant_id.

    The final assertion is an **exact set** over the live schema, so it is
    also the guard that catches a new directly-scoped table nobody registered
    in `TENANT_SCOPED_TABLES`.
    """
    with isolated_pg_engine.connect() as conn:
        scoped = set(
            conn.execute(
                text(
                    "SELECT table_name FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND column_name = 'tenant_id'"
                )
            )
            .scalars()
            .all()
        )

    for table in TENANT_INHERITED_TABLES:
        assert table not in scoped, f"{table} was denormalised with a tenant_id"

    # `user` is a global identity; `user_tenant_link` is the membership
    # table; `tenant_invitation` (APRAS-71) is the third table whose
    # `tenant_id` names a tenant from **outside** it -- it is issued by a
    # superuser on a route with no acting tenant and consumed by an
    # anonymous caller, so the column is a reference and not a
    # request-scoping key. None of the three is in `TENANT_SCOPED_TABLES`,
    # in `TENANT_SCOPED_MODELS` or in `0001`'s `_TENANT_SCOPED_TABLES`.
    assert scoped == set(TENANT_SCOPED_TABLES) | {
        "user_tenant_link",
        "tenant_invitation",
    }


