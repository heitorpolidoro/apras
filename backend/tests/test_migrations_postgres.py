"""Postgres-only validation of the Alembic history (APRAS-58, APRAS-66).

The history used to be 39 revision modules; APRAS-58 replaced it with one
autogenerated revision, ``0001_initial_schema``, produced from the final
``SQLModel.metadata``. APRAS-66 added the second, ``0002_tenant_slug``: the
rule that a new column goes *inside* ``0001`` held only while ``0001`` had
never been applied, and production applied it on 2026-09-19 (APRAS-59).
APRAS-71 added the third, ``0003_tenant_invitation``, under the same rule.

So there is a chain again, and it is a **line**: one root, one head, no
branch. This module asserts that shape, that the history at head builds
*exactly* the schema the models describe, that it seeds *exactly* the default
tenant and its six legacy roles, and that it round-trips.

It runs against a real PostgreSQL and never against SQLite, which stores enum
columns as a plain ``VARCHAR``, enforces no native constraint, and would let
a divergence between the migration and the models pass unnoticed. The whole
module self-skips unless ``TEST_POSTGRES_URL`` points at a reachable database
it is allowed to destroy -- every fixture runs ``DROP SCHEMA public
CASCADE``. CI is therefore the source of truth, and
``scripts/assert_no_skips.py`` refuses a run in which the module skipped.

    docker run -d --rm -p 55432:5432 \\
        -e POSTGRES_PASSWORD=postgres -e POSTGRES_DB=apras_test \\
        -e POSTGRES_INITDB_ARGS="--encoding=UTF8 --locale=C" \\
        postgres:16-alpine

    TEST_POSTGRES_URL=postgresql://postgres:postgres@localhost:55432/apras_test \\
        SECRET_KEY=test uv run pytest tests/test_migrations_postgres.py -v

The cluster must be UTF-8: the migration seeds ``Condomínio Padrão``.
"""

