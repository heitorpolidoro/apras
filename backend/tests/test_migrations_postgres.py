def test_the_global_uniques_stay_global(isolated_pg_engine):
    """`user.email`, `user.cpf`, `tenant.name` and `access_device.device_key`
    are install-wide: a second tenant must not be able to reuse them."""
    with isolated_pg_engine.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT t.relname AS table_name, i.relname AS index_name, "
                "  pg_get_indexdef(i.oid) AS definition "
                "FROM pg_index x "
                "JOIN pg_class i ON i.oid = x.indexrelid "
                "JOIN pg_class t ON t.oid = x.indrelid "
                "JOIN pg_namespace n ON n.oid = t.relnamespace "
                "WHERE n.nspname = 'public' AND x.indisunique"
            )
        ).all()

    unique_definitions = {
        (row.table_name, row.definition)
        for row in rows
        if "tenant_id" not in row.definition
    }

    for table, column in (
        ("user", "email"),
        ("user", "cpf"),
        ("tenant", "name"),
        ("access_device", "device_key"),
    ):
        assert any(
            name == table and f"({column})" in definition
            for name, definition in unique_definitions
        ), f"{table}.{column} is no longer globally unique"


