def test_the_slug_column_is_not_null_and_uniquely_indexed(isolated_pg_engine):
    """The index is the real arbiter of a collision, so it is asserted here
    rather than inferred from the service that computes candidates."""
    with isolated_pg_engine.connect() as conn:
        nullable = conn.execute(
            text(
                "SELECT is_nullable FROM information_schema.columns "
                "WHERE table_schema = 'public' AND table_name = 'tenant' "
                "AND column_name = 'slug'"
            )
        ).scalar_one()
        definitions = (
            conn.execute(
                text(
                    "SELECT pg_get_indexdef(i.oid) FROM pg_index x "
                    "JOIN pg_class i ON i.oid = x.indexrelid "
                    "JOIN pg_class t ON t.oid = x.indrelid "
                    "JOIN pg_namespace n ON n.oid = t.relnamespace "
                    "WHERE n.nspname = 'public' AND t.relname = 'tenant' "
                    "AND x.indisunique"
                )
            )
            .scalars()
            .all()
        )

    assert nullable == "NO"
    assert any("(slug)" in definition for definition in definitions)

    with (
        pytest.raises(Exception, match=r"duplicate key|unique constraint"),
        isolated_pg_engine.begin() as conn,
    ):
        conn.execute(
            text(
                "INSERT INTO tenant (id, name, slug, is_active, created_at, "
                "updated_at) VALUES (:id, 'Outro', 'condominio-padrao', true, "
                "now(), now())"
            ),
            {"id": uuid.uuid4()},
        )


def test_rows_created_before_the_upgrade_are_backfilled_within_the_rule(
    migrated_pg_engine,
):
    """ER-4: a pre-existing two-character name yields `condominio`-something.

    The row is inserted while the database sits at `0001` -- before the
    column exists -- which is the only way to exercise the backfill rather
    than the model's construction-time fallback. A name of `AB` derives two
    characters, under the 3-64 floor, so it must come back as the
    `condominio` base plus whatever suffix the walk frees, never as `ab`.
    """
    _reset_to(migrated_pg_engine, ROOT_REVISION)

    short_id, punctuation_id = uuid.uuid4(), uuid.uuid4()
    with migrated_pg_engine.begin() as conn:
        for row_id, name in ((short_id, "AB"), (punctuation_id, "!!!")):
            conn.execute(
                text(
                    "INSERT INTO tenant (id, name, is_active, created_at, "
                    "updated_at) VALUES (:id, :name, true, now(), now())"
                ),
                {"id": row_id, "name": name},
            )

    _run_alembic("upgrade", "head")

    with migrated_pg_engine.connect() as conn:
        slugs = dict(conn.execute(text("SELECT id, slug FROM tenant")).all())

    assert slugs[DEFAULT_TENANT_ID] == "condominio-padrao"
    backfilled = {slugs[short_id], slugs[punctuation_id]}
    assert backfilled == {"condominio", "condominio-2"}
    assert len(set(slugs.values())) == len(slugs)
    low, high = _SLUG_BOUNDS
    for slug in slugs.values():
        assert _SLUG_RULE.fullmatch(slug), slug
        assert low <= len(slug) <= high, slug

    _reset_to(migrated_pg_engine, "head")


