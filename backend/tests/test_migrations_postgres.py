def _revision_modules() -> list[pathlib.Path]:
    """Every ``.py`` under ``versions/`` that is not the package marker."""
    return sorted(p for p in _VERSIONS_DIR.glob("*.py") if p.name != "__init__.py")


def _module_constant(path: pathlib.Path, name: str):
    """Read a module-level literal by ``ast``, without importing the module.

    Importing ``backend/alembic/versions/`` would shadow the real
    third-party ``alembic`` library (see `_run_alembic`).
    """
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        targets = (
            [node.target]
            if isinstance(node, ast.AnnAssign)
            else getattr(node, "targets", [])
        )
        for target in targets:
            if isinstance(target, ast.Name) and target.id == name:
                return ast.literal_eval(node.value)
    raise AssertionError(f"{name} not found in {path}")


def _live_tables(engine) -> set[str]:
    with engine.connect() as conn:
        return set(
            conn.execute(
                text(
                    "SELECT table_name FROM information_schema.tables "
                    "WHERE table_schema = 'public' AND table_type = 'BASE TABLE'"
                )
            )
            .scalars()
            .all()
        )


def _live_columns(engine) -> dict[str, dict[str, bool]]:
    """``{table: {column: is_nullable}}`` for the whole ``public`` schema."""
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT table_name, column_name, is_nullable "
                "FROM information_schema.columns WHERE table_schema = 'public'"
            )
        ).all()
    live: dict[str, dict[str, bool]] = {}
    for row in rows:
        live.setdefault(row.table_name, {})[row.column_name] = row.is_nullable == "YES"
    return live


