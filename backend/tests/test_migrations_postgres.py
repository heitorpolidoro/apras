def test_versions_holds_exactly_the_expected_revision_modules():
    """The directory is the history: no stray, no leftover, no duplicate."""
    modules = _revision_modules()

    assert [p.name for p in modules] == [f"{slug}.py" for slug in EXPECTED_HISTORY]


def test_the_history_is_a_line_from_one_root_within_the_version_num_limit():
    """One root, each later revision pointing at its predecessor, every slug
    short enough for `alembic_version.version_num`."""
    previous = None
    for expected_slug in EXPECTED_HISTORY:
        module = _VERSIONS_DIR / f"{expected_slug}.py"
        revision = _module_constant(module, "revision")

        assert revision == expected_slug
        assert len(revision) <= _REVISION_LENGTH_LIMIT
        assert _module_constant(module, "down_revision") == previous
        previous = revision

    assert previous == HEAD_REVISION


def test_no_revision_imports_anything_from_app():
    """APRAS-66 D-E, widened by APRAS-71 to **every** revision in the history.

    A live `from app.core.slug import slugify` would silently rewrite history
    the day a later task changes `slugify`, and importing under `alembic/`
    also shadows the third-party library. `0001` sets the precedent by
    re-declaring `DEFAULT_TENANT_ID` and `LEGACY_ROLE_NAMES` as literals and
    `0002` by carrying a frozen copy of the slug derivation. The claim is
    asserted by `ast` rather than by grep so an
    `importlib.import_module("app...")` could not sneak past it either.

    The loop replaces the single-module check: a revision that is no longer
    the head is no less frozen, and the case count is unchanged by it.
    """
    offenders = {}
    for slug in EXPECTED_HISTORY:
        module = _VERSIONS_DIR / f"{slug}.py"
        tree = ast.parse(module.read_text(encoding="utf-8"), filename=str(module))

        imported = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                imported.add(node.module or "")
            elif isinstance(node, ast.Call):
                function = node.func
                name = getattr(function, "attr", getattr(function, "id", ""))
                if name in {"import_module", "__import__"}:
                    imported.update(
                        arg.value for arg in node.args if isinstance(arg, ast.Constant)
                    )

        bad = {name for name in imported if name == "app" or name.startswith("app.")}
        if bad:
            offenders[slug] = sorted(bad)

    assert not offenders, f"revisions importing application code: {offenders}"


def test_upgrade_downgrade_base_and_upgrade_again_all_succeed(migrated_pg_engine):
    """`downgrade base` empties the schema, and the migration replays.

    A migration that can only run once on a fresh database hides its own
    breakage until the day someone rolls back.
    """
    _reset_to(migrated_pg_engine, "head")
    assert _live_tables(migrated_pg_engine) - {"alembic_version"}

    _run_alembic("downgrade", "base")
    assert _live_tables(migrated_pg_engine) <= {"alembic_version"}

    _run_alembic("upgrade", "head")
    assert _live_tables(migrated_pg_engine) - {"alembic_version"}
    with migrated_pg_engine.connect() as conn:
        assert (
            conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
            == HEAD_REVISION
        )


